# =============================================================================
# 文件：generate_n60_csv.py
# 作用：生成 N60 相控阵的「离线优化表」CSV 文件
# =============================================================================
# 【这个程序是干嘛的？—— 项目背景（小白必读）】
#
# 这个比赛项目做的是一台「相控阵」设备：用 60 个麦克风（声音传感器）
# 摆成一个碗的形状，通过给每个麦克风的信号做不同的「延迟」和「幅度加权」，
# 可以让这 60 个麦克风像一支"无形的电子枪"一样，把接收灵敏度集中到
# 空间的某一个点上（叫做"聚焦"），或者朝着某个方向"看"（叫做"波束偏转"）。
#
# 本文件只做一件很简单的事：
#   把"目标点在 6 种距离 × 13 种角度 下，每个麦克风应该给多大幅度"，
#   提前计算好，写进一个 CSV 表格文件里，存到硬盘上。
#   以后上位机（n60_beam_params.py）运行的时候，直接查这张表就能拿到
#   幅度值，不用现场重新算 —— 这就是"离线优化表"的含义。
#
# 【术语速查】
#   阵元（element）：一个麦克风。本设备共 60 个。
#   子阵（unit）：把 60 个阵元分成 5 组，每组 12 个，叫一个子阵。
#   指向性（directivity）：麦克风对不同方向的声音，灵敏度不一样。
#       这个项目用的麦克风，正对着它的声音最灵敏（增益 1.0），
#       偏 35° 时灵敏度掉到一半（-6dB），这就是"指向性衰减模型"。
# =============================================================================

# -----------------------------------------------------------------------------
# 第一部分：导入需要用到的"工具包"
# -----------------------------------------------------------------------------
# import 是 Python 的"导入"语句，意思是从别人写好的代码库里把功能拿进来用。
# 这三行分别导入了三个标准库（Python 自带的，不用额外安装）：
import os   # os = operating system，操作系统工具：用来操作文件路径、创建文件夹等
import csv  # csv = 逗号分隔值，专门用来读写 CSV 表格文件（Excel 能直接打开）
import math # math = 数学函数库，提供 sin/cos/sqrt 等数学计算

# -----------------------------------------------------------------------------
# 第二部分：N60 阵列的"严格几何参数"（这些是硬件设计定的，不能乱改）
# -----------------------------------------------------------------------------

# 总通道数：60 路（5 个子阵 × 每个子阵 12 个阵元 = 60）
CHANNEL_COUNT = 60

# 5 个子阵，每个子阵整体在水平方向偏转的角度（单位：度）。
# 也就是说：5 组麦克风，一组朝 -45°、一组朝 -22.5°、中间一组正对前方 0°……
# 这样围成一个扇形，组合起来就是"碗"的形状。
UNIT_ANGLES_DEG = [-45.0, -22.5, 0.0, 22.5, 45.0]

# 碗的半径（单位：毫米）。这 60 个麦克风的圆心都落在
# 半径为 176.445 毫米的球面上，所以整体是个"碗"。
BOWL_RADIUS_MM = 176.445

# 每个子阵内部，12 个阵元的"局部坐标"（单位：毫米）。
# 局部坐标的意思是：把子阵的中心当作 (0, 0)，每个阵元相对中心往右/往左多少、
# 往上/往下多少。列表里每一项是 (x, y) 一对数字：
#   第一个数 x：水平方向偏移（正 = 右边，负 = 左边）
#   第二个数 y：垂直方向偏移（正 = 上方，负 = 下方）
# 例如第一项 (0.000, 0.000) 表示"正中心的阵元"，
# 第二项 (14.280, 10.958) 表示"中心偏右 14.28mm、偏上 10.958mm 的阵元"。
N12_LOCAL_COORDS = [
    (0.000, 0.000), (14.280, 10.958), (-10.958, 14.280), (-14.280, -10.958),
    (10.958, -14.280), (35.097, 8.011), (15.620, 32.435), (-15.620, 32.435),
    (-35.097, 8.011), (-28.146, -22.446), (0.000, -36.000), (28.146, -22.446)
]


# -----------------------------------------------------------------------------
# 第三部分：定义函数 —— 算出 60 个阵元在三维空间里的"绝对坐标"
# -----------------------------------------------------------------------------
# def 是 Python 的"定义函数"关键字。函数就像一个"加工厂"：
# 给它输入（参数），它按步骤加工，最后用 return 把结果交出来。
# 这个函数没有参数（括号里是空的），它会直接算出结果返回。
def generate_n60_geometry():
    """获取60路阵元的真实三维空间绝对坐标 (米)

    返回值是一个列表（list），里面按顺序装着 60 个阵元的坐标，
    每一项是 (x, y, z) 三个数字组成的三元组，单位是"米"。
    """
    # geometry 是"几何"的意思，这里用空列表来装最终结果
    geometry = []

    # enumerate() 是 Python 内置函数：一边取出列表里的每一项，一边给它们编号。
    # 这里 unit_id 拿到的是编号 0~4（第几个子阵），angle_deg 拿到的是角度值。
    for unit_id, angle_deg in enumerate(UNIT_ANGLES_DEG):
        # math.radians() 把"度"换算成"弧度"。
        # 原因：Python 的数学函数（sin、cos 等）只认弧度，不认度。
        # 弧度和度是角度的两种计量单位：360° = 2π 弧度。
        theta = math.radians(angle_deg)

        # 下面算的是"这个子阵的中心点"落在碗面上的坐标（单位：米）。
        # 因为碗是一个球面的一部分，中心点位置由"半径 × 三角函数"决定：
        #   cx（中心的 x 坐标）= 半径 × sin(水平偏角)
        #   cz（中心的 z 坐标）= -半径 × cos(水平偏角)   （负号表示碗口朝前）
        # 注意 / 1000.0 是把毫米换算成米（1 米 = 1000 毫米）。
        cx = (BOWL_RADIUS_MM * math.sin(theta)) / 1000.0
        cz = (-BOWL_RADIUS_MM * math.cos(theta)) / 1000.0

        # 现在遍历这个子阵内部的 12 个阵元。
        # lx、ly 是局部坐标（相对子阵中心），单位也是毫米。
        for lx, ly in N12_LOCAL_COORDS:
            # 把局部坐标"叠加"到子阵中心坐标上，就得到阵元的绝对坐标。
            # 因为子阵本身偏转了 theta 角，所以水平方向的偏移 lx
            # 也要跟着旋转：沿 x 方向的分量是 lx×cos(θ)，沿 z 方向的分量是 lx×sin(θ)。
            # （可以这样理解：一个点在斜面上"往右走"，实际效果是既往前又往旁边）
            gx = cx + (lx * math.cos(theta)) / 1000.0  # 绝对 x 坐标（米）
            gy = ly / 1000.0                            # 绝对 y 坐标（米），垂直方向不受旋转影响
            gz = cz + (lx * math.sin(theta)) / 1000.0   # 绝对 z 坐标（米）

            # append() 是列表的方法：把一项加到列表末尾。
            # 这里把 (x, y, z) 三元组存进 geometry。
            geometry.append((gx, gy, gz))

    # return 把最终结果交还给调用者。这里 geometry 里正好有 5×12=60 个坐标。
    return geometry


# -----------------------------------------------------------------------------
# 第四部分：定义主函数 —— 生成并保存 CSV 优化表
# -----------------------------------------------------------------------------
def create_physics_based_optimized_table():
    # ---------- 第一步：确定输出文件的存放位置 ----------
    # os.path.abspath(__file__) 拿到"当前这个 .py 文件"的绝对路径（含文件名）。
    # os.path.dirname(...)     再取它的上一级目录（去掉文件名）。
    # os.path.join(a, "..", "b") 把路径拼接起来，".." 表示"上一级目录"。
    # 合起来就是：到仓库根目录下的 analysis_outputs 文件夹里去找文件。
    output_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "analysis_outputs")

    # os.makedirs() 创建文件夹；exist_ok=True 表示"如果文件夹已存在也不要报错"。
    os.makedirs(output_dir, exist_ok=True)

    # 拼接出 CSV 文件的完整路径，文件名说明这张表的内容：
    # n60_5x12 = 60 通道、5 子阵 × 12 阵元；focus = 聚焦表；dbc_margin = 带 3.5 次方衰减余量。
    csv_path = os.path.join(output_dir, "n60_5x12_focus_table_dbc_margin.csv")

    # ---------- 第二步：准备要计算的所有"目标点"参数 ----------
    # 先调用上面的函数，拿到 60 个阵元的真实坐标。
    coords = generate_n60_geometry()

    # 6 种目标距离（单位：毫米）：0.5米、1米、1.5米、2米、3米、5米。
    distances = [500, 1000, 1500, 2000, 3000, 5000]

    # range(开始, 结束, 步长)：生成一个整数序列，注意"结束"是不包含的。
    # range(-30, 35, 5) 生成：-30, -25, -20, ..., 30（一共 13 个），
    # 也就是水平方位角从 -30° 到 +30°，每隔 5° 取一个。
    azimuths = range(-30, 35, 5) # -30 到 +30 度

    # print() 在控制台输出文字，f"..." 是"格式化字符串"：
    # 花括号 {} 里的内容会被替换成变量的值，方便调试时看程序走到哪一步了。
    print(f"正在基于三维物理法向 (3.5次方模型) 重构 N60 离线优化表...")

    # ---------- 第三步：打开文件，准备写入 ----------
    # with open(...) as f: 是 Python 标准的文件读写写法。
    #   mode='w'      = write 写入模式（会清空旧内容重新写）
    #   newline=''    = 避免 Windows 下 CSV 出现多余空行
    #   encoding='utf-8' = 用 UTF-8 编码，保证中文能正常保存
    # with 的好处：无论中间是否出错，文件最后都会自动关闭，不用手动管。
    with open(csv_path, mode='w', newline='', encoding='utf-8') as f:
        # 定义表头（每一列叫什么名字）：
        #   distance_mm = 目标距离（毫米）
        #   az_deg      = 水平方位角（度）
        #   el_deg      = 俯仰角（度），本脚本固定为 0
        #   gain_floor  = 增益下限（本脚本固定为 0）
        #   score       = 评分（本脚本固定为 1）
        #   success     = 是否成功（本脚本固定为 True）
        #   amp_00 ~ amp_59 = 60 个通道各自的幅度值（0.0 ~ 1.0）
        # [f'amp_{i:02d}' for i in range(60)] 是"列表推导式"：
        #   一种用一行循环生成列表的写法，等价于：
        #   names = []
        #   for i in range(60):
        #       names.append(f'amp_{i:02d}')
        #   其中 {i:02d} 表示把数字 i 补成至少 2 位（如 0 → "00"，5 → "05"）。
        fieldnames = ['distance_mm', 'az_deg', 'el_deg', 'gain_floor', 'score', 'success'] + [f'amp_{i:02d}' for i in range(60)]

        # csv.DictWriter：按"字典"的方式写 CSV。
        # 后面每写一行，给它一个字典，它就会自动按 fieldnames 的顺序把值填进对应列。
        writer = csv.DictWriter(f, fieldnames=fieldnames)

        # writeheader()：把表头那一行写进文件。
        writer.writeheader()

        # ---------- 第四步：双重循环，穷举所有 (距离 × 角度) 组合 ----------
        # 外层循环：遍历 6 种距离。
        for dist_mm in distances:
            # 内层循环：遍历 13 种方位角。
            # 这样一共会算 6 × 13 = 78 个目标点。
            for az in azimuths:
                # 先构造这一行的"基本信息"（距离/角度/标志位）。
                # 注意 Python 的字典（dict）用花括号，里面是"键: 值"成对出现。
                row = {
                    'distance_mm': dist_mm, 'az_deg': az, 'el_deg': 0,
                    'gain_floor': 0.0, 'score': 1.0, 'success': 'True'
                }

                # ---------- 第五步：算出"目标点"在三维空间里的坐标 ----------
                # 毫米换算成米。
                dist_m = dist_mm / 1000.0
                # 角度换算成弧度。
                az_rad = math.radians(az)
                # 简化处理：俯仰角 el 固定为 0，所以目标点永远在"水平面"（X-Z 平面）上。
                # 目标点坐标 = 距离 × 方向：
                #   x = 距离 × sin(方位角)   （左右）
                #   y = 0                    （高度不变，因为没俯仰）
                #   z = 距离 × cos(方位角)   （前后）
                # 这是一条"极坐标转直角坐标"的标准公式。
                target_m = (dist_m * math.sin(az_rad), 0.0, dist_m * math.cos(az_rad))

                # ---------- 第六步（核心）：对 60 个通道逐一计算幅度 ----------
                # for ch in range(60)：ch 取 0、1、2、...、59，代表第几个通道。
                for ch in range(60):
                    # 通道编号 → 所属子阵编号。
                    # // 是"整除"（只取整数部分，不要小数）。
                    # 因为每 12 个通道属于同一个子阵：通道 0~11 属于子阵 0，12~23 属于子阵 1……
                    unit_id = ch // 12
                    # 取这个子阵的水平偏角，转成弧度。
                    theta_rad = math.radians(UNIT_ANGLES_DEG[unit_id])

                    # 阵元的"法向量"：垂直于麦克风表面的方向。
                    # 麦克风表面朝向 = 它所在位置碗面的法线方向。
                    # 碗是斜的，所以法向量在水平方向有分量 nx，前后方向有分量 nz：
                    #   nx = -sin(θ)，nz = cos(θ)
                    # （θ 是子阵偏转角。垂直方向 ny 恒为 0，因为碗只在水平方向倾斜）
                    nx = -math.sin(theta_rad)
                    ny = 0.0
                    nz = math.cos(theta_rad)

                    # 取出这个通道阵元的实际空间坐标（元组解包：一次取出三个数）。
                    mx, my, mz = coords[ch]

                    # "阵元 → 目标点"的方向向量：
                    # 用目标点坐标减去阵元坐标，就得到从阵元指向目标的向量。
                    vx, vy, vz = target_m[0] - mx, target_m[1] - my, target_m[2] - mz

                    # math.hypot(a, b) = 计算 sqrt(a² + b²)（直角三角形斜边长）。
                    # 这里嵌套使用，算出向量的长度（三维空间的"斜边"），即阵元到目标的距离。
                    v_len = math.hypot(math.hypot(vx, vy), vz)

                    # 如果距离大于 0（阵元没和目标点重合）：
                    if v_len > 0:
                        # 把向量每个分量除以长度 → 得到"单位向量"（长度正好为 1）。
                        # 单位向量只表示"方向"，不再包含"多远"的信息。
                        vx, vy, vz = vx/v_len, vy/v_len, vz/v_len

                        # 核心数学：两个单位向量的"点积"（dot product）。
                        # 点积 = vx*nx + vy*ny + vz*nz，它的几何意义是"两个方向夹角的余弦值"：
                        #   完全同向（阵元正对目标）→ 点积 = 1
                        #   完全垂直              → 点积 = 0
                        #   背对目标              → 点积 < 0
                        dot = vx*nx + vy*ny + vz*nz

                        # 【终极修复】：把点积代入衰减模型，得到这个阵元该给的幅度。
                        #   max(0.0, dot)：如果点积是负数（阵元背对目标），就强制取 0，
                        #                  因为幅度不能是负数。
                        #   ** 3.5：对结果做 3.5 次方运算。
                        #   这个 3.5 次方是结合原厂麦克风实测数据拟合出来的衰减曲线：
                        #   实测 -6dB@35°，用这个幂次能很好地逼近真实的指向性衰减，
                        #   让偏离目标的阵元幅度快速下降，从而压低旁瓣（不需要的方向上的杂音）。
                        amp = max(0.0, dot) ** 3.5
                    else:
                        # 极端情况：阵元和目标点重合（几乎不会发生），幅度给满 1.0。
                        amp = 1.0

                    # round(x, 4)：把小数保留 4 位，写入这一行的对应通道列。
                    # 字典按"键"存值：row['amp_00']、row['amp_01']……
                    row[f'amp_{ch:02d}'] = round(amp, 4)

                # ---------- 第七步：把这一整行写入 CSV 文件 ----------
                # writerow() 会按表头顺序，把字典里的值写成一行文本。
                writer.writerow(row)

    # ---------- 第八步：收尾提示 ----------
    # 全部写完、文件自动关闭后，在控制台打印完成信息和文件的绝对路径。
    # ✅ 只是一个好看的符号；os.path.abspath() 把相对路径转成绝对路径方便查找。
    print(f"✅ 生成完毕！真实的 3.5 次方物理指向性已固化入表：\n{os.path.abspath(csv_path)}")


# -----------------------------------------------------------------------------
# 第五部分：程序入口
# -----------------------------------------------------------------------------
# 每个 Python 文件都可以直接运行，也可以被别的文件"导入"。
# if __name__ == "__main__": 是 Python 的经典写法：
#   - 直接运行本文件时，Python 会把特殊变量 __name__ 设成 "__main__"，
#     于是条件成立，执行下面的代码。
#   - 如果是被别的文件 import 导入，__name__ 是文件名本身，条件不成立，
#     就不会执行，避免"导入一次就自动跑一遍"。
if __name__ == "__main__":
    # 调用主函数，程序正式开始干活。
    create_physics_based_optimized_table()
